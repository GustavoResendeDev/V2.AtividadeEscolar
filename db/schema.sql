-- Banco da Nova Era Barbearia (PostgreSQL: Supabase em produção, PGlite nos testes e no npm start).
-- Idempotente: pode rodar várias vezes (o deploy roda a cada publicação).

CREATE EXTENSION IF NOT EXISTS pgcrypto; -- crypt()/gen_salt(): senhas com bcrypt calculadas no banco

CREATE TABLE IF NOT EXISTS barbeiros (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           TEXT    NOT NULL UNIQUE,
  especialidade  TEXT    NOT NULL,
  ativo          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS servicos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            TEXT    NOT NULL UNIQUE,
  categoria       TEXT    NOT NULL,
  duracao_min     INTEGER NOT NULL CHECK (duracao_min > 0),
  preco_centavos  INTEGER NOT NULL CHECK (preco_centavos >= 0),
  ativo           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS clientes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT        NOT NULL,
  telefone   TEXT        UNIQUE,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS agendamentos (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo           TEXT        NOT NULL UNIQUE,
  cliente_id       INTEGER     NOT NULL REFERENCES clientes(id),
  servico_id       INTEGER     NOT NULL REFERENCES servicos(id),
  barbeiro_id      INTEGER     NOT NULL REFERENCES barbeiros(id),
  data             TEXT        NOT NULL CHECK (data ~ '^\d{4}-\d{2}-\d{2}$'),
  inicio_min       INTEGER     NOT NULL,
  fim_min          INTEGER     NOT NULL,
  preco_centavos   INTEGER     NOT NULL,
  status           TEXT        NOT NULL DEFAULT 'pendente'
                   CHECK (status IN ('pendente', 'confirmado', 'concluido', 'cancelado', 'faltou')),
  consentimento_em TIMESTAMPTZ NOT NULL,
  criado_em        TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fim_min > inicio_min)
);
CREATE INDEX IF NOT EXISTS idx_agendamentos_agenda ON agendamentos (data, barbeiro_id, status);
CREATE INDEX IF NOT EXISTS idx_agendamentos_cliente ON agendamentos (cliente_id);

-- Serviços de cada agendamento (o cliente pode escolher mais de um).
-- agendamentos.servico_id continua guardando o primeiro, por compatibilidade.
CREATE TABLE IF NOT EXISTS agendamento_servicos (
  agendamento_id  INTEGER NOT NULL REFERENCES agendamentos(id) ON DELETE CASCADE,
  servico_id      INTEGER NOT NULL REFERENCES servicos(id),
  ordem           INTEGER NOT NULL,
  duracao_min     INTEGER NOT NULL,
  preco_centavos  INTEGER NOT NULL,
  PRIMARY KEY (agendamento_id, servico_id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         TEXT    NOT NULL,
  email        TEXT    NOT NULL,
  senha_hash   TEXT    NOT NULL,
  papel        TEXT    NOT NULL CHECK (papel IN ('admin', 'barbeiro')),
  barbeiro_id  INTEGER REFERENCES barbeiros(id),
  ativo        BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_email ON usuarios (lower(email));

-- Sessões do painel: o navegador guarda só um token aleatório; aqui fica o hash dele.
CREATE TABLE IF NOT EXISTS sessoes (
  token_hash  TEXT    PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_em   BIGINT  NOT NULL -- milissegundos desde 1970
);

-- Tentativas de login erradas por IP (o Worker roda em várias máquinas, então o contador fica no banco).
CREATE TABLE IF NOT EXISTS tentativas_login (
  chave   TEXT    PRIMARY KEY,
  inicio  BIGINT  NOT NULL,
  falhas  INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS historico_status (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agendamento_id  INTEGER     NOT NULL REFERENCES agendamentos(id) ON DELETE CASCADE,
  de              TEXT,
  para            TEXT        NOT NULL,
  usuario_id      INTEGER     REFERENCES usuarios(id),
  em              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Supabase publica o schema public pela Data API (chave anon). Nada aqui é para ela:
-- RLS ligado e sem políticas = ninguém lê pela API; o Worker entra como postgres e não é afetado.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['barbeiros', 'servicos', 'clientes', 'agendamentos', 'agendamento_servicos',
                           'usuarios', 'sessoes', 'tentativas_login', 'historico_status'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON %I FROM anon, authenticated', t);
    END IF;
  END LOOP;
END $$;

